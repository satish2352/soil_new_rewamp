/**
 * Finds Tailwind utility classes that the source references but the compiled
 * stylesheet never generated.
 *
 * Silently-dropped utilities are dangerous: the element simply renders without
 * the style, which can look fine on one background and broken on another. Run
 * this after `npm run build`.
 */
import fs from 'node:fs';
import path from 'node:path';

const assets = 'dist/assets';
if (!fs.existsSync(assets)) {
  console.error('No dist/ found — run `npm run build` first.');
  process.exit(1);
}

const css = fs
  .readdirSync(assets)
  .filter((f) => f.endsWith('.css'))
  .map((f) => fs.readFileSync(path.join(assets, f), 'utf8'))
  .join('\n');

const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p) : [p];
  });

const sources = walk('src').filter((f) => /\.(jsx?|css)$/.test(f));

// Utilities carrying an opacity modifier, e.g. `bg-primary/85`.
const PATTERN =
  /\b((?:bg|text|border|from|via|to|ring|fill|stroke|placeholder|divide|shadow|outline)-[a-zA-Z]+(?:-[a-zA-Z0-9]+)*\/\d{1,3})(?![\w./-])/g;

const used = new Map();
for (const file of sources) {
  const src = fs.readFileSync(file, 'utf8');
  for (const m of src.matchAll(PATTERN)) {
    if (!used.has(m[1])) used.set(m[1], new Set());
    used.get(m[1]).add(path.basename(file));
  }
}

/*
  In the stylesheet the slash is escaped: `.bg-primary\/85{...}`.
  A variant prefix changes the selector to `.hover\:bg-primary\/85:hover`, and
  an `@apply` inlines the declarations with no class emitted at all — so match
  the escaped name anywhere, and require the next character not to be a digit
  so `/8` does not match `/80`.
*/
const escaped = (cls) => cls.replace(/\//g, '\\/');

// Utilities pulled in through @apply never appear as a selector of their own.
const appliedInCss = new Set();
for (const file of sources.filter((f) => f.endsWith('.css'))) {
  const src = fs.readFileSync(file, 'utf8');
  for (const m of src.matchAll(/@apply([^;]+);/g)) {
    for (const token of m[1].split(/\s+/)) {
      const t = token.trim();
      if (t) appliedInCss.add(t.replace(/^[a-z-]+:/, ''));
    }
  }
}

const missing = [];
for (const [cls, files] of used) {
  if (appliedInCss.has(cls)) continue;

  const needle = escaped(cls);
  let found = false;
  let i = css.indexOf(needle);
  while (i !== -1) {
    if (!/\d/.test(css[i + needle.length] || '')) {
      found = true;
      break;
    }
    i = css.indexOf(needle, i + 1);
  }
  if (!found) missing.push([cls, [...files]]);
}

console.log(`utilities with an opacity modifier : ${used.size}`);
console.log(`never generated by Tailwind        : ${missing.length}\n`);

if (missing.length) {
  const values = [...new Set(missing.map(([c]) => Number(c.split('/')[1])))].sort((a, b) => a - b);
  console.log('dropped opacity values:', values.join(', '), '\n');
  for (const [cls, files] of missing.sort()) {
    console.log(`  ${cls.padEnd(24)} ${files.join(', ')}`);
  }
  process.exitCode = 1;
} else {
  console.log('All opacity utilities resolved.');
}
